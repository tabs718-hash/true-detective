export function closedRoomReason(location: string, room: string): string {
  if (location === 'WHITMORE_OFFICE' && room === 'accounting') return 'Для предметной беседы о счетах пока нет достаточного основания.';
  if (location === 'WHITMORE_OFFICE') return 'Нора просит уточнить, какие рабочие материалы вам нужны, прежде чем открыть кабинет.';
  if (location === 'MANSION' && room === 'richard_home_study') return 'Элизабет пока не готова открыть личные записи мужа. Возможно, новые обстоятельства дадут повод вернуться к этому разговору.';
  if (location === 'MANSION') return 'Это личные помещения. Для осмотра нужны основания и согласие Элизабет.';
  return 'Для осмотра этого помещения пока нет согласия или достаточного основания.';
}
